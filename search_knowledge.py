def get_keywords(question, question_type):
    """Combine question words with Tamil topic terms."""
    q = normalize_text(question)

    words = [
        word for word in re.findall(r"[^\W_]+", q)
        if len(word) >= 3 and word not in STOP_WORDS
    ]

    words.extend(TOPIC_TERMS.get(question_type, []))

    keywords = []
    seen = set()

    for word in words:
        word = normalize_text(word)
        if word and word not in seen:
            keywords.append(word)
            seen.add(word)

    return keywords


def get_chunk_page(chunk):
    """Return the page number if the metadata contains one."""
    for key in ("page", "page_number", "source_page"):
        if chunk.get(key) is not None:
            return chunk[key]
    return None


def score_chunk(text, question_type, keywords):
    """Score a passage using keyword matches and topic-specific clues."""
    normalized = normalize_text(text)
    topic_terms = TOPIC_TERMS.get(question_type, [])

    matches = [
        term for term in keywords
        if normalize_text(term) in normalized
    ]

    topic_matches = [
        term for term in topic_terms
        if normalize_text(term) in normalized
    ]

    score = len(matches) + 2 * len(topic_matches)

    # Prefer explanatory passages for definition questions.
    if question_type in {
        "nakshatra_definition", "janma_nakshatra"
    }:
        if any(term in normalized for term in (
            "என்றால் என்ன", "தெரிந்து கொள்வோம்",
            "எவ்வாறு தெரிந்து"
        )):
            score += 5

        if (
            "பஞ்சாங்கம்" in normalized
            and "ஜன்ம நட்சத்திரம்" in normalized
        ):
            score += 5

        # Reduce the ranking of example horoscope passages.
        if any(term in normalized for term in (
            "அவள் கணவனின் ஜாதகம்",
            "இவர்களுக்கு நாம்",
            "தசப் பொருத்தம்"
        )):
            score -= 8

        if (
            "சித்தயோகம்" in normalized
            and "அமிர்த யோகம்" in normalized
        ):
            score -= 4

    # Prefer passages containing many distinct star names.
    if question_type == "nakshatra_list":
        name_count = sum(
            1 for name in STAR_NAMES
            if normalize_text(name) in normalized
        )
        score += name_count * 3

    if (
        question_type == "earthy_signs"
        and "நிலராசி" in normalized
    ):
        score += 8

    if (
        question_type == "panchangam"
        and "ஐந்து" in normalized
        and "திதி" in normalized
    ):
        score += 5

    return score, matches


def extract_relevant_excerpt(
    text, matched_terms, max_chars=MAX_CHARS
):
    """Return a bounded passage around a matched term."""
    text = str(text or "").strip()

    if len(text) <= max_chars:
        return text

    normalized = normalize_text(text)
    positions = []

    for term in matched_terms:
        position = normalized.find(normalize_text(term))
        if position >= 0:
            positions.append(position)

    start = max(0, min(positions) - 250) if positions else 0
    end = min(len(text), start + max_chars)

    return text[start:end].strip()


def search_knowledge(question, chunks, top_k=TOP_RESULTS):
    """Return several ranked passages for the question."""
    question_type = get_question_type(question)
    keywords = get_keywords(question, question_type)

    ranked = []

    for index, chunk in enumerate(chunks):
        text = chunk.get("text", "")

        if not text.strip():
            continue

        score, matches = score_chunk(
            text, question_type, keywords
        )

        if score > 0:
            ranked.append({
                "chunk_id": chunk.get(
                    "chunk_id", chunk.get("id", index)
                ),
                "page": get_chunk_page(chunk),
                "score": score,
                "text": extract_relevant_excerpt(text, matches),
                "_index": index
            })

    ranked.sort(
        key=lambda item: (item["score"], -item["_index"]),
        reverse=True
    )

    results = []
    seen = set()

    for item in ranked:
        signature = normalize_text(item["text"][:250])

        if signature in seen:
            continue

        seen.add(signature)

        results.append({
            key: value
            for key, value in item.items()
            if not key.startswith("_")
        })

        if len(results) >= top_k:
            break

    return results


def main():
    """Run retrieval tests in the terminal."""
    chunks = load_chunks()

    print(f"Loaded {len(chunks)} text chunks.")
    print("Ask a question in Tamil or English. Type 'exit' to stop.")

    while True:
        question = input("\nQuestion: ").strip()

        if question.casefold() in {"exit", "quit"}:
            print("Goodbye!")
            break

        if not question:
            print("Please enter a question.")
            continue

        results = search_knowledge(question, chunks)

        if not results:
            print("No matching passage found in the documents.")
            continue

        for number, result in enumerate(results, start=1):
            print(f"\n--- Relevant passage {number} ---")
            print(
                f"Chunk: {result['chunk_id']} | "
                f"Page: {result['page']} | "
                f"Score: {result['score']}"
            )
            print("=" * 70)
            print(result["text"])


if __name__ == "__main__":
    main()
